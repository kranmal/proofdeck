// Assign runs in bulk from the cycle page.
import { connect } from './uilib.mjs';
const t = await connect({ out: process.argv[2] });
const { check, js, sleep, api, go, click, text, count, submit, send } = t;
await send('Emulation.setFocusEmulationEnabled', { enabled: true });
await t.setup();
await api('/api/users', 'POST', { username: 'tess', display_name: 'Tess Tester', password: 'tess password 1', role: 'tester' });
await api('/api/users', 'POST', { username: 'rob', display_name: 'Rob Reviewer', password: 'rob password 12', role: 'tester' });
await js(`location.reload()`); await sleep(1200);
const cycles = await api('/api/projects/1/cycles');
const cy = cycles.find((c) => !c.adhoc);
await go(`#/cycles/${cy.id}`); await sleep(700);
check('cycle page has an Assign runs button', await js(`!!document.querySelector('[data-act=assign]')`));
await click('[data-act=assign]'); await sleep(400);
check('dialog lists people and the unassigned count', (await text('dialog')).includes('Tess Tester') && (await text('dialog')).includes('Only runs nobody has yet'));
await js(`document.querySelectorAll('dialog input[name=who]').forEach((c) => { if (/Tess|Rob/.test(c.parentElement.textContent)) c.click(); })`);
await submit(); await sleep(1000);
const runs = (await api(`/api/cycles/${cy.id}`)).executions;
const by = {};
for (const r of runs) by[r.assignee_id] = (by[r.assignee_id] || 0) + 1;
const people = await api('/api/users');
const ids = people.filter((u) => ['tess', 'rob'].includes(u.username)).map((u) => u.id);
check('runs are shared between the two people', ids.every((i) => by[i] >= 1) && Math.abs(by[ids[0]] - by[ids[1]]) <= 1, JSON.stringify(by));
check('the assignee drop-downs on the page show the new names', (await text('tbody')).includes('Tess Tester'));
await click('[data-act=assign]'); await sleep(400);
await js(`document.querySelector('dialog input[name=mode][value=clear]').click(); document.querySelector('dialog input[name=only][value=all]').click()`);
await submit(); await sleep(900);
check('clear removes every assignee', (await api(`/api/cycles/${cy.id}`)).executions.every((r) => !r.assignee_id));
check('no console errors', t.errors.filter((e) => !/status of (401|403|400|404)/.test(e)).length === 0, t.errors.join(' | '));
process.exit(t.finish() ? 1 : 0);
